import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import { env } from './config/env.js';
import authRoutes from './routes/authRoutes.js';
import inventoryRoutes from './routes/inventoryRoutes.js';
import workflowRoutes from './routes/workflowRoutes.js';
import deliveryRoutes from './routes/deliveryRoutes.js';
import expenseRoutes from './routes/expenseRoutes.js';
import reportRoutes from './routes/reportRoutes.js';
import historyRoutes from './routes/historyRoutes.js';
import employeeAdvanceRoutes from './routes/employeeAdvanceRoutes.js';
import supplierRoutes from './routes/supplierRoutes.js';
import { errorHandler } from './middleware/errorHandler.js';

export const app = express();
app.use(helmet());
app.use(cors({ origin: env.frontendUrl }));
app.use(express.json());
app.get('/api/health', (req, res) => res.json({ success: true, message: 'Broom Business API is running', data: { environment: env.nodeEnv } }));
app.use('/api/auth', authRoutes);
app.use('/api/inventory', inventoryRoutes);
app.use('/api', workflowRoutes);
app.use('/api/deliveries', deliveryRoutes);
app.use('/api/expenses', expenseRoutes);
app.use('/api/reports', reportRoutes);
app.use('/api/history', historyRoutes);
app.use('/api/employee-advances', employeeAdvanceRoutes);
app.use('/api/suppliers', supplierRoutes);
app.use((req, res) => res.status(404).json({ success: false, message: 'Route not found', error: 'NOT_FOUND' }));
app.use(errorHandler);
